export type StageId = `level-${number}` | 'secret';
export type Screen = 'menu' | 'desktop' | 'ending';
export type AppId = 'browser' | 'files' | 'terminal' | 'settings' | 'cookies' | 'journal' | 'achievements';
export type EndingChoice = 'escape' | 'become' | 'truth';
export type Clue = { id: string; title: string; description: string; location: string; relatedPuzzle: string; discoveredAt: string };
export type MemoryFragment = { id: string; text: string; stageId: StageId; discoveredAt: string };
export type GameNotification = { id: string; title: string; message: string; createdAt: string; read: boolean; tone: 'info' | 'warning' | 'story' };
export type SimCookie = { name: string; value: string; category: 'session' | 'memory' | 'identity' | 'system'; inspected: boolean; stageId?: StageId };
export type BrowserTab = { id: string; title: string; url: string; stack: string[]; historyIndex: number; openedAt: number; arrangement: string[]; submittedAt?: number };
export type HistoryEntry = { id: string; tabId: string; url: string; title: string; visitedAt: number; snapshot?: string; deleted?: boolean };
export type StageProgress = {
  flags: Record<string, boolean | number | string>;
  visited: string[];
  events: string[];
  selected: string[];
  sequence: string[];
  startedAt?: number;
  timerDeadline?: number;
};
export type SettingsState = { muted: boolean; musicEnabled: boolean; volume: number; reducedMotion: boolean; crtEffects: boolean; textScale: number };
export type GameStore = {
  screen: Screen;
  activeStageId: StageId;
  unlockedStages: StageId[];
  completedStages: StageId[];
  tabs: BrowserTab[];
  activeTabId: string;
  history: HistoryEntry[];
  bookmarks: string[];
  cookies: SimCookie[];
  clues: Clue[];
  memoryFragments: MemoryFragment[];
  achievements: string[];
  endingsSeen: EndingChoice[];
  chosenEnding?: EndingChoice;
  stageProgress: Partial<Record<StageId, StageProgress>>;
  notifications: GameNotification[];
  terminalLog: { id: string; input: string; output: string; at: number; kind: 'command' | 'system' }[];
  observerHeat: number;
  observerLastHost: string;
  observerPath: string[];
  windowState: Record<AppId, boolean>;
  minimizedWindows: AppId[];
  settings: SettingsState;
  newGamePlus: number;
  lastSavedAt: number;
  completionOverlay: boolean;
  showIntro: boolean;
  addNotification: (title: string, message: string, tone?: GameNotification['tone']) => void;
  dismissNotification: (id: string) => void;
  openWindow: (id: AppId) => void;
  closeWindow: (id: AppId) => void;
  minimizeWindow: (id: AppId) => void;
  toggleFullscreen: () => Promise<void>;
  startNewGame: () => void;
  continueGame: () => void;
  restartRun: () => void;
  openStage: (id: StageId) => void;
  beginStage: () => void;
  advanceStage: () => void;
  completeStage: () => void;
  navigate: (rawUrl: string, tabId?: string) => void;
  back: () => void;
  forward: () => void;
  refresh: () => void;
  openTab: (url?: string) => void;
  duplicateTab: (id: string) => void;
  closeTab: (id: string) => void;
  switchTab: (id: string) => void;
  toggleBookmark: (url?: string) => void;
  openBookmark: (url: string) => void;
  inspectCookie: (name: string) => void;
  toggleSelection: (item: string) => void;
  setProgressFlag: (key: string, value?: boolean | number | string) => void;
  appendSequence: (value: string) => void;
  resetSequence: () => void;
  setTabArrangement: (tabId: string, arrangement: string[]) => void;
  submitTabArrangement: (tabId: string) => void;
  recordSnapshot: (snapshotId: string) => void;
  discoverClue: (clue: Omit<Clue, 'discoveredAt'>) => void;
  discoverMemory: (fragment: Omit<MemoryFragment, 'discoveredAt'>) => void;
  addCookie: (cookie: SimCookie) => void;
  chooseMissingTab: () => void;
  restoreConversation: () => void;
  reconstructIdentity: () => void;
  selectEnding: (choice: EndingChoice) => void;
  executeCommand: (input: string) => void;
  spendHint: () => number;
  updateSettings: (settings: Partial<SettingsState>) => void;
  clearNotifications: () => void;
};
